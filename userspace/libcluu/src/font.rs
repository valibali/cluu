//! 8x16 CP437 font + single-cell rounded arc corner overrides.
//!
//! Font data is rasterized at build time from 0xProto v2.502 (OFL-1.1)
//! by `build.rs` into three glyph banks: Regular, Bold, Italic.
//! See `fonts/LICENSE-OFL.txt` for the font license.
//!
//! CP437 box-drawing and block element glyphs (0xB0..=0xDF) are kept from
//! the classic VGA font for consistent border/block rendering.
//! ARC_CORNERS overrides CP437 indices 0xF0..0xF3 with 4 single-cell
//! Unicode arc corner bitmaps (U+256D..U+2570). Box-drawing verticals
//! are thinned from 2px to 1px to match horizontal stroke width.
//!
//! Always go through `glyph_for_cp437` / `glyph_for_cp437_bold` /
//! `glyph_for_cp437_italic`; they fold the overrides in.

pub const GLYPH_W: usize = 8;
pub const GLYPH_H: usize = 16;
pub const GLYPH_ALPHA_SIZE: usize = GLYPH_W * GLYPH_H;

include!(concat!(env!("OUT_DIR"), "/font_0xproto.rs"));

