fn bits_to_alpha(bits: &[u8; GLYPH_H]) -> [u8; GLYPH_ALPHA_SIZE] {
    let mut alpha = [0u8; GLYPH_ALPHA_SIZE];
    for row in 0..GLYPH_H {
        for col in 0..GLYPH_W {
            if (bits[row] >> (7 - col)) & 1 != 0 {
                alpha[row * GLYPH_W + col] = 255;
            }
        }
    }
    alpha
}

#[inline]
fn raw_alpha_glyph(bank: &[u8; 32768], ch: u8) -> [u8; GLYPH_ALPHA_SIZE] {
    if (0xB0..=0xDF).contains(&ch) {
        let idx = (ch - 0xB0) as usize * GLYPH_H;
        let mut bits = [0u8; GLYPH_H];
        bits.copy_from_slice(&FONT_CP437_BOXES[idx..idx + GLYPH_H]);
        bits_to_alpha(&bits)
    } else {
        let idx = (ch as usize) * GLYPH_ALPHA_SIZE;
        let mut alpha = [0u8; GLYPH_ALPHA_SIZE];
        alpha.copy_from_slice(&bank[idx..idx + GLYPH_ALPHA_SIZE]);
        alpha
    }
}

#[inline]
pub fn glyph_alpha_for_cp437(ch: u8) -> [u8; GLYPH_ALPHA_SIZE] {
    if (0xF0..=0xF3).contains(&ch) {
        return bits_to_alpha(&ARC_CORNERS[(ch - 0xF0) as usize]);
    }
    if let Some(g) = thinned_box_glyph(ch) {
        return bits_to_alpha(&g);
    }
    raw_alpha_glyph(&FONT_0XPROTO_REGULAR_ALPHA, ch)
}

#[inline]
pub fn glyph_alpha_for_cp437_bold(ch: u8) -> [u8; GLYPH_ALPHA_SIZE] {
    if (0xF0..=0xF3).contains(&ch) {
        return bits_to_alpha(&ARC_CORNERS[(ch - 0xF0) as usize]);
    }
    if let Some(g) = thinned_box_glyph(ch) {
        return bits_to_alpha(&g);
    }
    raw_alpha_glyph(&FONT_0XPROTO_BOLD_ALPHA, ch)
}

#[inline]
pub fn glyph_alpha_for_cp437_italic(ch: u8) -> [u8; GLYPH_ALPHA_SIZE] {
    if (0xF0..=0xF3).contains(&ch) {
        return bits_to_alpha(&ARC_CORNERS[(ch - 0xF0) as usize]);
    }
    if let Some(g) = thinned_box_glyph(ch) {
        return bits_to_alpha(&g);
    }
    raw_alpha_glyph(&FONT_0XPROTO_ITALIC_ALPHA, ch)
}

fn thinned_box_glyph(ch: u8) -> Option<[u8; GLYPH_H]> {
    const V: u8 = 0b00001000;
    const DV: u8 = 0b00010100;
    const H_R: u8 = 0b00001111;
    const H_L: u8 = 0b11111000;
    const DH_R: u8 = 0b00011111;
    const DH_L: u8 = 0b11111100;
    match ch {
        0xB3 => Some([V; 16]),
        0xBA => Some([DV; 16]),
        0xDA => Some([0, 0, 0, 0, 0, 0, 0, H_R, V, V, V, V, V, V, V, V]),
        0xBF => Some([0, 0, 0, 0, 0, 0, 0, H_L, V, V, V, V, V, V, V, V]),
        0xC0 => Some([V, V, V, V, V, V, V, H_R, 0, 0, 0, 0, 0, 0, 0, 0]),
        0xD9 => Some([V, V, V, V, V, V, V, H_L, 0, 0, 0, 0, 0, 0, 0, 0]),
        0xC9 => Some([0, 0, 0, 0, 0, DH_R, DV, DH_R, DV, DV, DV, DV, DV, DV, DV, DV]),
        0xBB => Some([0, 0, 0, 0, 0, DH_L, DV, DH_L, DV, DV, DV, DV, DV, DV, DV, DV]),
        0xC8 => Some([DV, DV, DV, DV, DV, DH_R, DV, DH_R, 0, 0, 0, 0, 0, 0, 0, 0]),
        0xBC => Some([DV, DV, DV, DV, DV, DH_L, DV, DH_L, 0, 0, 0, 0, 0, 0, 0, 0]),
        _ => None,
    }
}
