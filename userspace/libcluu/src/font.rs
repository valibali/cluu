fn bits_to_alpha(bits: &[u8; GLYPH_H]) -> [u8; GLYPH_ALPHA_SIZE] {
    let mut alpha = [0u8; GLYPH_ALPHA_SIZE];
    for row in 0..GLYPH_H {
        for col in 0..GLYPH_W {
            if (bits[row] >> (7 - col)) & 1 != 0 {
                alpha[row * GLYPH_W + col] = 255;
            }
        }
    }
    alpha
}

#[inline]
fn raw_alpha_glyph(bank: &[u8; 32768], ch: u8) -> [u8; GLYPH_ALPHA_SIZE] {
    if (0xB0..=0xDF).contains(&ch) {
        let idx = (ch - 0xB0) as usize * GLYPH_H;
        let mut bits = [0u8; GLYPH_H];
        bits.copy_from_slice(&FONT_CP437_BOXES[idx..idx + GLYPH_H]);
        bits_to_alpha(&bits)
    } else {
        let idx = (ch as usize) * GLYPH_ALPHA_SIZE;
        let mut alpha = [0u8; GLYPH_ALPHA_SIZE];
        alpha.copy_from_slice(&bank[idx..idx + GLYPH_ALPHA_SIZE]);
        alpha
    }
}

#[inline]
pub fn glyph_alpha_for_cp437(ch: u8) -> [u8; GLYPH_ALPHA_SIZE] {
    if (0xF0..=0xF3).contains(&ch) {
        return bits_to_alpha(&ARC_CORNERS[(ch - 0xF0) as usize]);
    }
    if let Some(g) = extra_hand_glyph(ch) {
        return bits_to_alpha(&g);
    }
    if let Some(g) = thinned_box_glyph(ch) {
        return bits_to_alpha(&g);
    }
    raw_alpha_glyph(&FONT_0XPROTO_REGULAR_ALPHA, ch)
}

